"""Regenerate Android icon vectors from artwork/hraell.svg (standard library only)."""

from pathlib import Path
import re
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[2]
source = ET.parse(ROOT / "artwork/hraell.svg").getroot()
x, y, width, height = map(float, source.attrib["viewBox"].split())
path = source.find("{http://www.w3.org/2000/svg}path")
tx, ty = map(float, re.fullmatch(r"translate\(([-\d.]+),([-\d.]+)\)", path.attrib["transform"]).groups())

for destination, size, color in (
    ("manager/src/main/res/drawable/ic_hraell.xml", 108, "@color/ic_launcher_fg"),
    ("daemon/src/main/res/drawable/ic_hraell_monochrome.xml", 24, "#FFFFFF"),
):
    (ROOT / destination).write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by manager/tools/generate_icon.py from artwork/hraell.svg. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp" android:height="{size}dp"\n'
        f'    android:viewportWidth="{width:g}" android:viewportHeight="{height:g}">\n'
        f'    <group android:translateX="{tx-x:g}" android:translateY="{ty-y:g}">\n'
        f'        <path android:fillColor="{color}" android:fillType="evenOdd"\n'
        f'            android:pathData="{path.attrib["d"]}" />\n'
        '    </group>\n</vector>\n',
        encoding="utf-8",
    )
